// D12: Android OS backups never carry the app's SQLite database (step-counter D57, cycle-tracker review M4, vitals-log
// D60; pattern of photo-vault plugins/with-vault-backup-rules.js). "Nothing leaves the phone" except the files the user
// makes with the app's own backup; an OS copy of the database (to Google Drive, or to a new phone) is a privacy leak,
// and a half-restored state (settings or a SecureStore key without its database, or the reverse) only creates broken
// states. Three layers, every variant:
// - `android.allowBackup: false` in app.config.ts (Expo's own step writes android:allowBackup; API 24–30: no cloud
//   backup and no device-to-device copy at all; API 31+: no cloud backup);
// - android:fullBackupContent → res/xml/backup_rules.xml (API 24–30; excludes the database folder in case allowBackup
//   is ever switched back on);
// - android:dataExtractionRules → res/xml/data_extraction_rules.xml (API 31+, read even with allowBackup="false":
//   device-to-device transfer during phone setup still runs there, so the folder is excluded from BOTH cloud-backup and
//   device-transfer).
// expo-sqlite keeps every database in `Context.getFilesDir()/SQLite` (SQLiteModule.kt `defaultDatabaseDirectory`), i.e.
// domain "file", path "SQLite/" — NOT domain "database". The SecureStore preferences are excluded too, the same line
// expo-secure-store's own rule files carry: when an app adds expo-secure-store, its plugin sees these files, leaves them
// in place (console warning) and its keys stay out of backups; pass `configureAndroidBackup: false` to silence it.
// An app that wants device transfer of its data (a product call, e.g. mood-journal D62) removes the <device-transfer>
// exclusion here and says so in its DECISIONS. iOS: src/lib/backup-exclusion.ts (modules/backup-exclusion).
// Checked by plugins/backup-rules.test.js; on a device by `aapt dump xmltree` of the release APK.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const SQLITE_DIR = 'SQLite/';
const FULL_BACKUP_XML = 'backup_rules';
const EXTRACTION_XML = 'data_extraction_rules';

// loyalty-cards D49: also the card photos (files/cards/, src/lib/files.ts CARDS_DIR) and the widget barcode PNGs
// (files/widgets/, src/lib/widgets.ts): without the database they are orphans, and they carry card numbers.
const APP_DIRS = ['cards/', 'widgets/'];
const EXCLUDES = [
  `<exclude domain="file" path="${SQLITE_DIR}"/>`,
  ...APP_DIRS.map((dir) => `<exclude domain="file" path="${dir}"/>`),
  '<exclude domain="sharedpref" path="SecureStore"/>',
];
const indent = (spaces) => EXCLUDES.map((line) => `${' '.repeat(spaces)}${line}`);

const fullBackupContent = () =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/with-backup-rules.js (D12). Android 11 and older: the database never goes into a backup. -->',
    '<full-backup-content>',
    ...indent(2),
    '</full-backup-content>',
    '',
  ].join('\n');

const dataExtractionRules = () =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/with-backup-rules.js (D12). Android 12+: no cloud backup and no device transfer of the database. -->',
    '<data-extraction-rules>',
    '  <cloud-backup>',
    ...indent(4),
    '  </cloud-backup>',
    '  <device-transfer>',
    ...indent(4),
    '  </device-transfer>',
    '</data-extraction-rules>',
    '',
  ].join('\n');

/** Points the <application> at both rule files. allowBackup itself comes from app.config.ts (`android.allowBackup`). */
function setBackupAttributes(manifest) {
  const app = manifest.application?.[0];
  if (!app) throw new Error('with-backup-rules: no <application> in AndroidManifest.xml');
  app.$ = {
    ...app.$,
    'android:fullBackupContent': `@xml/${FULL_BACKUP_XML}`,
    'android:dataExtractionRules': `@xml/${EXTRACTION_XML}`,
  };
  return manifest;
}

function withBackupRules(config) {
  config = withAndroidManifest(config, (cfg) => {
    setBackupAttributes(cfg.modResults.manifest);
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${FULL_BACKUP_XML}.xml`), fullBackupContent());
      fs.writeFileSync(path.join(dir, `${EXTRACTION_XML}.xml`), dataExtractionRules());
      return cfg;
    },
  ]);
}

module.exports = withBackupRules;
module.exports.setBackupAttributes = setBackupAttributes;
module.exports.fullBackupContent = fullBackupContent;
module.exports.dataExtractionRules = dataExtractionRules;
module.exports.SQLITE_DIR = SQLITE_DIR;
module.exports.APP_DIRS = APP_DIRS;
module.exports.FULL_BACKUP_XML = FULL_BACKUP_XML;
module.exports.EXTRACTION_XML = EXTRACTION_XML;
